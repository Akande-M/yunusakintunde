const GUESSES: [RegExp, string][] = [
  [/biograph|about|profile/i, "user"],
  [/achievement/i, "trophy"],
  [/recognition|award|honou?r/i, "award"],
  [/bill|motion|legislat/i, "scroll"],
  [/committee|oversight/i, "checklist"],
  [/intervention|development/i, "hand-heart"],
  [/outreach|health|medical/i, "stethoscope"],
  [/infrastructure|project|road/i, "construction"],
  [/skill|job|empower/i, "briefcase"],
  [/campaign|mobili[sz]/i, "megaphone"],
  [/stakeholder|partner/i, "handshake"],
  [/engagement|community|town ?hall/i, "users"],
  [/news|update|press/i, "newspaper"],
  [/gallery|photo|media/i, "images"],
  [/video/i, "video"],
  [/event/i, "calendar"],
  [/home/i, "home"],
];

export function navIcon(label: string, icon?: string | null): LucideIcon {
  if (icon && NAV_ICONS[icon]) return NAV_ICONS[icon].Icon;
  const guess = GUESSES.find(([re]) => re.test(label))?.[1];
  return NAV_ICONS[guess ?? "page"]!.Icon;
}
